import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { modules } from "../modules.config";
import type { ModuleConfig } from "../modules.config";

/**
 * Reads modules.config.ts (the single source of truth) and generates:
 *   1. apps/shell/rewrites.generated.js - the Next.js Multi-Zones rewrite rule for
 *      EVERY module, pointing to its path (internal) or its own domain (standalone).
 *   2. apps/<module>/base-path.generated.js - for every "internal" module ONLY, the
 *      Next.js `basePath` that module's OWN next.config.ts must apply. REQUIRED by
 *      Next.js Multi-Zones: shell's rewrite above proxies "/<module>/:path*" straight
 *      through to the module's origin at the SAME path - so the module must itself
 *      serve everything (pages AND its own _next/static/* assets) under that same
 *      "/<module>" prefix, or those requests 404 once routed through the shell (this
 *      was a real, confirmed-but-unnoticed bug: it never shows up when building/running
 *      a module standalone, only when actually proxied through the shell). "standalone"
 *      modules own their own domain's root, so they never get this file.
 *   3. infra/swarm/<module>.yml - a Docker Swarm stack file for EVERY module
 *      (every module gets its own deployable service regardless of zone - see
 *      best-practice-structure.md's foundational principle). The ONLY thing that
 *      differs by zone is the Traefik routing label AND the healthcheck path inside the
 *      file (an "internal" module's own routes, including /api/health, live under its
 *      basePath - see point 2 above).
 *
 * Run with: pnpm run generate-infra
 * CI check (fails if committed files are stale): pnpm run generate-infra -- --check
 *
 * Per the project's own research (audit-best-practice-structure.md section on
 * codegen patterns): generated files are COMMITTED to git (reviewable diff), with
 * this --check mode run in CI to catch drift - never generate silently at deploy time.
 */

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const CHECK_MODE = process.argv.includes("--check");

function envVarName(moduleName: string): string {
  return `ZONE_URL_${moduleName.toUpperCase().replace(/-/g, "_")}`;
}

function rewriteDestination(mod: ModuleConfig): string {
  if (mod.zone === "standalone") {
    return `https://${mod.domain}/:path*`;
  }
  // Internal module: destination origin comes from an env var at runtime (points at
  // wherever that module's container actually runs - differs between dev/staging/prod
  // and even between a bare-VM PM2 setup and a real Swarm service), falling back to a
  // sane local-dev default so `pnpm run dev` works without extra setup.
  return (
    "${process.env." + envVarName(mod.name) + ' ?? "http://localhost:3101"}/' + mod.name + "/:path*"
  );
}

/** The Next.js `basePath` an "internal" module must serve itself under - `null` for
 * "standalone" modules, which own the root of their own domain instead. */
function basePathFor(mod: ModuleConfig): string | null {
  return mod.zone === "internal" ? `/${mod.name}` : null;
}

/** Where /api/health actually lives for this module - under its basePath for
 * "internal" modules, at the root for "standalone" modules. Swarm's healthcheck hits
 * the container directly on its own port, so it must know the real path. */
function healthCheckPath(mod: ModuleConfig): string {
  const basePath = basePathFor(mod);
  return basePath ? `${basePath}/api/health` : "/api/health";
}

function generateBasePathFile(mod: ModuleConfig): string {
  const basePath = basePathFor(mod);
  return `// AUTO-GENERATED by scripts/generate-infra.ts from modules.config.ts - DO NOT EDIT BY HAND.
// Re-run "pnpm run generate-infra" after changing modules.config.ts.
//
// REQUIRED for Next.js Multi-Zones: this module's own next.config.ts MUST pass this
// value as "basePath" to withBaseConfig() - otherwise its pages and _next/static/*
// assets 404 once proxied through the shell (see generate-infra.ts's module doc comment).

module.exports = "${basePath}";
`;
}

function generateShellRewrites(): string {
  const rules = modules.map((mod) => ({
    source: `/${mod.name}/:path*`,
    // placeholder swapped for the real template-literal destination below
    destination: `__DEST_${mod.name}__`,
  }));

  let body = JSON.stringify(rules, null, 2);
  for (const mod of modules) {
    body = body.replace(`"__DEST_${mod.name}__"`, "`" + rewriteDestination(mod) + "`");
  }

  return `// AUTO-GENERATED by scripts/generate-infra.ts from modules.config.ts - DO NOT EDIT BY HAND.
// Re-run "pnpm run generate-infra" after changing modules.config.ts.

/** @type {() => Promise<import('next').NextConfig['rewrites']>} */
module.exports = async function rewrites() {
  return ${body};
};
`;
}

function generateSwarmStack(mod: ModuleConfig): string {
  // Plain backtick, no backslash needed - YAML double-quoted strings don't treat
  // backtick as special, so a literal `\`` in the generated file is actually WRONG
  // YAML (confirmed by a real prettier parse error when this was escaped as \\\`).
  const traefikRule =
    mod.zone === "standalone" ? `Host(\`${mod.domain}\`)` : `PathPrefix(\`/${mod.name}\`)`;
  const healthPath = healthCheckPath(mod);

  return `# AUTO-GENERATED by scripts/generate-infra.ts from modules.config.ts - DO NOT EDIT BY HAND.
# Re-run "pnpm run generate-infra" after changing modules.config.ts.
# zone: ${mod.zone}${mod.zone === "standalone" ? ` (domain: ${mod.domain})` : " (path-based, same domain as shell)"}

version: "3.8"

services:
  ${mod.name}-web:
    image: registry.archetype-group.com/${mod.name}-web:\${IMAGE_TAG}
    networks:
      - traefik-public
    deploy:
      replicas: 2
      update_config:
        order: start-first
        failure_action: rollback
        delay: 5s
        monitor: 20s
      rollback_config:
        order: start-first
      restart_policy:
        condition: any
      resources:
        limits:
          cpus: "1.0"
          memory: 512M
        reservations:
          cpus: "0.25"
          memory: 256M
      labels:
        - "traefik.enable=true"
        - "traefik.http.routers.${mod.name}.rule=${traefikRule}"
        - "traefik.http.routers.${mod.name}.entrypoints=websecure"
        - "traefik.http.routers.${mod.name}.tls.certresolver=myresolver"
        - "traefik.http.services.${mod.name}.loadbalancer.server.port=3000"
        - "traefik.http.services.${mod.name}.loadbalancer.healthcheck.path=${healthPath}"
        - "traefik.http.services.${mod.name}.loadbalancer.healthcheck.interval=10s"
        - "traefik.http.services.${mod.name}.loadbalancer.healthcheck.timeout=3s"
    healthcheck:
      test: ["CMD", "wget", "--spider", "-q", "http://localhost:3000${healthPath}"]
      interval: 10s
      timeout: 3s
      retries: 3
      start_period: 15s

networks:
  traefik-public:
    external: true
`;
}

/**
 * Formats generated content with this repo's own Prettier config before writing -
 * otherwise `pnpm exec prettier --check .` (run in CI, see ci-frontend.yml) would
 * ALWAYS flag these files as unformatted, since hand-built template-string output
 * rarely matches Prettier's exact formatting rules by coincidence (confirmed with a
 * real prettier parse/format mismatch on the first version of this script).
 */
async function formatGenerated(filePath: string, content: string): Promise<string> {
  const config = await prettier.resolveConfig(filePath);
  return prettier.format(content, { ...config, filepath: filePath });
}

async function writeIfChanged(path: string, rawContent: string): Promise<boolean> {
  const content = await formatGenerated(path, rawContent);
  const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (existing === content) return false;

  if (CHECK_MODE) {
    console.error(`✗ stale (or missing): ${path}`);
    return true;
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`✓ wrote ${path}`);
  return true;
}

async function main() {
  let drift = false;

  drift =
    (await writeIfChanged(
      join(ROOT, "apps/shell/rewrites.generated.js"),
      generateShellRewrites(),
    )) || drift;

  for (const mod of modules) {
    if (mod.zone === "internal") {
      drift =
        (await writeIfChanged(
          join(ROOT, `apps/${mod.name}/base-path.generated.js`),
          generateBasePathFile(mod),
        )) || drift;
    }

    drift =
      (await writeIfChanged(join(ROOT, `infra/swarm/${mod.name}.yml`), generateSwarmStack(mod))) ||
      drift;
  }

  if (CHECK_MODE && drift) {
    console.error(
      "\nGenerated infra files are out of date. Run `pnpm run generate-infra` and commit the result.",
    );
    process.exit(1);
  }
}

main();
